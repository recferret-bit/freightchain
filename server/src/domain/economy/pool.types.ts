import type { PaidTierId } from '../rides/ride-tier.js';

/* Data shapes of an escrowed prize pool (docs/paid-tickets-plan.md §0 and §2.6). The CHAIN is the source of truth: a Pool row is the server's mirror of the on-chain account,
   kept in step by the program-log watcher and PoolSyncService. Lamports are plain numbers (a pool holds far below 2^53 lamports ≈ 9 million SOL). The rules (state machine,
   sale window, caps) live in the Pool entity of the pools workstream; this file only fixes the shape the ports speak. */

export const POOL_STATUSES = ['open', 'active', 'refunding', 'settled', 'cancelled'] as const;
/** open = selling, minimum not reached · active = minimum reached, rides count · refunding = failed / cancelled, every buyer can claim back · settled = closed · cancelled = never opened */
export type PoolStatus = (typeof POOL_STATUSES)[number];

export interface PoolProps {
  /** the on-chain pool_id (u32) – chosen at creation, not generated by the database */
  id: number;
  /** the Pool PDA */
  address: string;
  tier: PaidTierId;
  label: string;
  priceLamports: number;
  /** the pool goes active when this many tickets are sold */
  minTickets: number;
  /** 0 = unlimited */
  maxTickets: number;
  maxPerWallet: number;
  /** the minimum must be sold by this moment, else the pool fails and everyone is refunded */
  prepDeadline: Date;
  /** entries and counted rides end here */
  playDeadline: Date;
  prizeBps: number;
  seedBps: number;
  feeBps: number;
  feeTreasury: string;
  seedTreasury: string;
  status: PoolStatus;
  ticketsSold: number;
  buyers: number;
  /** the escrow balance, sponsorships included */
  vaultLamports: number;
  sponsored: number;
  /** the weekly round it ranks in – set when the pool goes active */
  roundId: number | null;
  createdAt: Date;
  /** the last time the server compared this row with the account on chain */
  syncedAt: Date | null;
}
