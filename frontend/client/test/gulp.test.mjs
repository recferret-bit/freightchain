import test from 'node:test';
import assert from 'node:assert/strict';

const { st } = await import('../js/state.js');
const { gulp, resetGulp, syncGulp, toggleGas, toggleFix, sendCode, pushDigit, confirmCode } = await import('../js/phone/gulp-state.js');
const { chipHull } = await import('../js/state.js');

test('a GULP visit latches only when the truck stops, and resets at the next bay', () => {
  resetGulp();
  st.s = 0; st.hull = 40; st.mend = null; st.tankBonus = 0; st.scratches = [{ a: 1 }]; st.cracks = [{ a: 1 }];
  syncGulp(50, false);
  assert.equal(gulp.phase, 'idle');
  syncGulp(50, true);
  assert.equal(gulp.phase, 'pick');
  assert.equal(gulp.at, true);
  assert.equal(gulp.bay, 50);
  toggleGas('half');
  syncGulp(null, false);
  assert.equal(gulp.at, false);
  assert.equal(gulp.gas, 'half');
  assert.equal(sendCode(), false);
  syncGulp(200, false);
  assert.equal(gulp.bay, 50);
  syncGulp(50, true);
  assert.equal(sendCode(), true);
  assert.match(gulp.code, /^\d{4}$/);
  const code = gulp.code;
  syncGulp(50, true);
  assert.equal(sendCode(), false);
  assert.equal(gulp.code, code);
  gulp.typed = code === '0000' ? '1111' : '0000';
  assert.equal(confirmCode(), false);
  assert.equal(gulp.typed, '');
  assert.equal(gulp.phase, 'code');
  assert.equal(gulp.wrong, true);
  syncGulp(null, false);
  for (const ch of code) pushDigit(ch);
  assert.equal(confirmCode(), false);
  syncGulp(50, true);
  assert.equal(confirmCode(), true);
  assert.equal(gulp.phase, 'done');
  assert.equal(gulp.code, '');
  assert.equal(gulp.gas, null);
  assert.equal(st.hull, 40);
  assert.ok(st.tankBonus > 0);
  assert.equal(st.mend, null);
  assert.equal(st.scratches.length, 1);
  syncGulp(50, true);
  assert.equal(gulp.phase, 'done');
  syncGulp(90, true);
  assert.equal(gulp.phase, 'pick');
  assert.equal(gulp.bay, 90);
  toggleFix();
  toggleGas('fill');
  assert.equal(sendCode(), true);
  gulp.typed = gulp.code;
  const hull = st.hull;
  assert.equal(confirmCode(), true);
  assert.equal(st.hull, hull);
  assert.equal(st.mend, 100);
  assert.equal(st.scratches.length, 0);
  assert.equal(st.cracks.length, 0);
  assert.equal(st.tankBonus, 1 - (0.85 - 0.45 * 0));
  chipHull(10);
  assert.equal(st.hull, hull - 10);
  assert.equal(st.mend, 90);
  resetGulp();
  assert.equal(gulp.phase, 'idle');
});
