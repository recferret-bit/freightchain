import type { PaidTierId } from '../rides/ride-tier.js';

/* Data shapes of an escrowed prize pool (docs/spec/pool.md). The CHAIN is the source of truth: a Pool row is the server's mirror of the on-chain account,
   kept in step by the program-log watcher and PoolSyncService. Lamports are plain numbers (a pool holds far below 2^53 lamports ≈ 9 million SOL). The rules (state machine,
   sale window, caps) live in the Pool entity of the pools workstream; this file only fixes the shape the ports speak. */

export const POOL_STATUSES = ['open', 'active', 'refunding', 'settled', 'cancelled'] as const;
/** open = selling, minimum not reached · active = minimum reached, rides count · refunding = failed, cancelled by the admin or expired unsettled – every buyer can claim back ·
 *  settled = an active pool closed and split · cancelled = a refunding pool closed after every refund (terminal; the program's status 4) */
export type PoolStatus = (typeof POOL_STATUSES)[number];

/** Where the server's payout job stands with an active pool (the server's own, not on chain – the chain records only what was paid):
 *  pending = not due yet · waiting_review = rides of the pool still wait for an admin's decision · held = an admin put it on hold ·
 *  paying = prizes are being sent · paid = every prize sent and the pool closed · no_winners = no verified ride ranks, the admin decides · error = the last pass failed (note says why) */
/** `committed` (program v4): the winners root is on chain and public until its lock ends (`payFrom`) – nobody is paid before */
export const PAYOUT_STATES = ['pending', 'waiting_review', 'held', 'committed', 'paying', 'paid', 'no_winners', 'error'] as const;
export type PayoutState = (typeof PAYOUT_STATES)[number];

/** An admin's hold on a pool's payout (signed + audited); the payout job pays nothing while it is set. */
export interface PoolHold {
  by: string;
  at: Date;
  note: string | null;
}

export interface PoolProps {
  /** the on-chain pool_id (u32) – chosen at creation, not generated by the database */
  id: number;
  /** the Pool PDA */
  address: string;
  tier: PaidTierId;
  label: string;
  priceLamports: number;
  /** the pool goes active when this many tickets are sold */
  minTickets: number;
  /** 0 = unlimited */
  maxTickets: number;
  maxPerWallet: number;
  /** the end of the SALE window: no ticket is sold from here on (open or active); under the minimum the pool fails and everyone is refunded */
  prepDeadline: Date;
  /** counted rides end here (ticket sales already closed at `prepDeadline`) */
  playDeadline: Date;
  /** the end of the review window: no prize is paid and the pool is not closed before it (the program enforces it) */
  payoutAt: Date;
  /** Null/absent = createdAt. Sales are refused before this. */
  opensAt?: Date | null;
  /** Null/absent = prepDeadline (the on-chain sales close). */
  salesCloseAt?: Date | null;
  /** Null/absent = play close − 75 min. */
  lastStartAt?: Date | null;
  /** Null/absent = playDeadline. */
  playCloseAt?: Date | null;
  /** Null/absent = payoutAt. commit_winners waits until this instant. */
  validationUntil?: Date | null;
  prizeBps: number;
  seedBps: number;
  feeBps: number;
  /** omitted = 0. The Pool table does not store it yet; a chain read keeps it on the in-memory mirror only. v5 pools have no referral leg. */
  referralBps?: number;
  /**
   * v5: the pool's snapshotted player-share cap. Absent on a Postgres reload (no column): `prizeBound` then counts every ticket.
   * The chain still rejects a winners root above `prize_share`. Present only until the next save, from a chain read in this process.
   */
  maxPlayerShareBps?: number;
  /** v5 snapshot. Absent on a Postgres reload. `buy_ticket` is enforced on chain, not by the mirror. */
  paidTicketsEnabled?: boolean;
  feeTreasury: string;
  seedTreasury: string;
  status: PoolStatus;
  ticketsSold: number;
  buyers: number;
  /** the ESCROW: what the vault holds above its rent-exempt minimum (sponsorships included) */
  vaultLamports: number;
  sponsored: number;
  /** the weekly round it ranks in – set when the pool goes active */
  roundId: number | null;
  /** the ROAD seed every ride of this pool is driven on (31-bit, like Ride.seed): the server's own, drawn once when the pool enters the mirror and never changed,
      so every ticket holder drives the same route, start hour, layout and holes (ride-rules.ts worldFor, domain/road). Not the `seedBps` money split. */
  rideSeed: number;
  createdAt: Date;
  /** the last time the server compared this row with the account on chain */
  syncedAt: Date | null;
  /** the payout job's state and why (the server's own) */
  payoutState: PayoutState;
  payoutNote: string | null;
  /** an admin's hold on the payout, null = none */
  hold: PoolHold | null;
  /** base64 SHA-256 commitment the program made when the pool opened (chain-events.ts PoolCreatedFields) */
  seedCommitment?: string | null;
  /** the SlotHashes entry behind it: the bank hash (base58 – the column is named blockhash) and its slot */
  blockhash?: string | null;
  slot?: bigint | number | null;
  // ---- program v4 (audit WP5), mirrored from the Pool account
  /** the slot whose hash seals the road; > 0 with no seedCommitment = not sealed yet: no ride is served (L4); null = an account without it */
  sealSlot?: number | null;
  /** the committed winners root (base64), when, and the first moment it pays (H5-B); null = none on chain */
  winnersRoot?: string | null;
  committedAt?: Date | null;
  payFrom?: Date | null;
}
